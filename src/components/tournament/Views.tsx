export function ParticipantsView({ b }: { b: TournamentBundle }) {
  const players = confirmedParticipants(b);
  if (!players.length) return <EmptyState icon={<Users className="h-8 w-8" />} title={t('No participants yet')} description={t('Registered players will appear here.')} />;
  const groupOf = new Map(b.groupMembers.map((gm) => [gm.participantId, b.groups.find((g) => g.id === gm.groupId)?.name]));
  const sorted = [...players].sort((a, c) => a.createdAt.localeCompare(c.createdAt));
  return (
    <ul className="grid gap-2 sm:grid-cols-2 lg:grid-cols-3">
      {sorted.map((p, i) => (
        <li key={p.id} className="flex items-center gap-3 rounded-[var(--radius-control)] border border-line bg-surface px-3 py-2.5">
          <span className="w-6 text-right text-xs tabular text-subtle">{i + 1}</span>
          <div className="min-w-0 flex-1">
            <p className="truncate text-sm font-medium">{p.displayName}</p>
            <TeamLine team={p.team} />
          </div>
          {p.seed !== null && <span className="text-xs text-muted">{t('Seed {n}', { n: p.seed })}</span>}
          {groupOf.get(p.id) && <span className="rounded bg-surface-3 px-1.5 py-0.5 text-xs text-muted">{tr(groupOf.get(p.id) as string)}</span>}
        </li>
      ))}
    </ul>
  );
}

export const TIEBREAK_LABEL: Record<Tiebreaker, string> = {
  goal_diff: 'goal difference',
  goals_for: 'goals scored',
  wins: 'wins',
  h2h_points: 'head-to-head points',
  h2h_goal_diff: 'head-to-head goal difference',
  h2h_goals_for: 'head-to-head goals',
};

export function StandingsView({ b }: { b: TournamentBundle }) {
  const names = nameMap(b.participants);
  const tables = groupTables(b);
  if (!tables.length) return <EmptyState icon={<Table2 className="h-8 w-8" />} title={t('Groups have not been drawn yet')} description={t('The standings will appear after the group draw and update as results are recorded.')} />;
  const s = b.tournament.settings;
  return (
    <div className="space-y-4">
      <p className="text-sm text-muted">
        {t('Top {n} of each group qualify. Win {w} · Draw {d} · Loss {l}.', { n: s.advancePerGroup, w: s.pointsWin, d: s.pointsDraw, l: s.pointsLoss })}{' '}
        {t('Ties: {order} → seed / registration order.', { order: s.tiebreakers.map((x) => t(TIEBREAK_LABEL[x])).join(' → ') })}
      </p>
      <div className="grid gap-4 lg:grid-cols-2">
        {tables.map((tb) => <GroupTable key={tb.groupId} table={tb} names={names} advance={s.advancePerGroup} />)}
      </div>
    </div>
  );
}

interface Section { key: string; title: string; matches: Match[] }

function sections(b: TournamentBundle, stage: 'all' | 'group' | 'knockout', groupId: string): Section[] {
  const out: Section[] = [];
  if (stage !== 'knockout') {
    const groups = [...b.groups].sort((a, c) => a.index - c.index).filter((g) => groupId === 'all' || g.id === groupId);
    const gm = b.matches.filter((m) => m.stage === 'group' && groups.some((g) => g.id === m.groupId));
    const rounds = [...new Set(gm.map((m) => m.round))].sort((a, c) => a - c);
    for (const r of rounds) {
      const ms = gm.filter((m) => m.round === r).sort((a, c) => (groups.findIndex((g) => g.id === a.groupId) - groups.findIndex((g) => g.id === c.groupId)) || a.slot - c.slot);
      out.push({ key: `g${r}`, title: t('Group stage · Matchday {n}', { n: r }), matches: ms });
    }
  }
  if (stage !== 'group' && groupId === 'all') {
    for (const r of knockoutRounds(b)) out.push({ key: `k${r.round}${r.name}`, title: tr(r.name), matches: r.matches });
  }
  return out;
}

export function MatchesView({ b, onEdit }: { b: TournamentBundle; onEdit?: (m: Match) => void }) {
  const [stage, setStage] = useState<'all' | 'group' | 'knockout'>('all');
  const [groupId, setGroupId] = useState('all');
  const [status, setStatus] = useState<'all' | MatchStatus | 'open'>('all');
  const names = useMemo(() => nameMap(b.participants), [b.participants]);
  const groupName = useMemo(() => new Map(b.groups.map((g) => [g.id, tr(g.name)])), [b.groups]);
  if (!b.matches.length) return <EmptyState icon={<CalendarX2 className="h-8 w-8" />} title={t('No matches have been scheduled yet.')} description={t('Fixtures are generated by the organizer once registration closes.')} />;
  const filtered = sections(b, stage, groupId)
    .map((s) => ({ ...s, matches: s.matches.filter((m) => status === 'all' || (status === 'open' ? m.status !== 'completed' && m.status !== 'cancelled' : m.status === status)) }))
    .filter((s) => s.matches.length);
  const hasGroups = b.groups.length > 0;
  return (
    <div className="space-y-5">
      <div className="flex flex-wrap gap-2" role="group" aria-label={t('Filter matches')}>
        {hasGroups && (
          <Select aria-label={t('Stage')} value={stage} onChange={(e) => { setStage(e.target.value as typeof stage); setGroupId('all'); }} className="w-auto">
            <option value="all">{t('All stages')}</option>
            <option value="group">{t('Group stage')}</option>
            <option value="knockout">{t('Knockout')}</option>
          </Select>
        )}
        {hasGroups && stage !== 'knockout' && (
          <Select aria-label={t('Group')} value={groupId} onChange={(e) => setGroupId(e.target.value)} className="w-auto">
            <option value="all">{t('All groups')}</option>
            {[...b.groups].sort((a, c) => a.index - c.index).map((g) => <option key={g.id} value={g.id}>{tr(g.name)}</option>)}
          </Select>
        )}
        <Select aria-label={t('Status')} value={status} onChange={(e) => setStatus(e.target.value as typeof status)} className="w-auto">
          <option value="all">{t('Any status')}</option>
          <option value="open">{t('Still to play')}</option>
          <option value="in_progress">{t('Live')}</option>
          <option value="completed">{t('Completed')}</option>
          <option value="postponed">{t('Postponed')}</option>
          <option value="cancelled">{t('Cancelled')}</option>
        </Select>
      </div>
      {!filtered.length && <EmptyState title={t('No matches match these filters.')} />}
      {filtered.map((s) => (
        <section key={s.key} aria-label={s.title}>
          <h3 className="mb-2 text-xs font-semibold uppercase tracking-wider text-muted">{s.title}</h3>
          <div className="grid gap-2 lg:grid-cols-2">
            {s.matches.map((m) => (
              <MatchCard key={m.id} m={m} names={names} onEdit={onEdit} label={m.groupId ? groupName.get(m.groupId) : m.isThirdPlace ? tr(roundName(1, true)) : undefined} />
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}

export function PlayoffsView({ b, onEdit }: { b: TournamentBundle; onEdit?: (m: Match) => void }) {
  const names = nameMap(b.participants);
  const rounds = knockoutRounds(b);
  if (!rounds.length) {
    const s = b.tournament.settings;
    const qualifiers = s.groupCount * s.advancePerGroup;
    const shape = knockoutShapeNote(qualifiers);
    return (
      <EmptyState
        icon={<GitBranch className="h-8 w-8" />}
        title={t('The knockout bracket has not been generated yet.')}
        description={b.tournament.format === 'groups_knockout'
          ? `${t('It is created once every group match is completed. {n} players will advance.', { n: qualifiers })}${shape ? ' ' + tr(shape) : ''}`
          : t('The organizer generates the bracket after registration closes.')}
      />
    );
  }
  return (
    <div className="space-y-5">
      <ChampionBanner podium={podium(b)} names={names} />
      <Bracket rounds={rounds} names={names} onEdit={onEdit} />
    </div>
  );
}

export function NextMatches({ b }: { b: TournamentBundle }) {
  const names = nameMap(b.participants);
  const upcoming = b.matches
    .filter((m) => (m.status === 'scheduled' || m.status === 'in_progress') && m.homeId && m.awayId)
    .sort((a, c) => (a.status === 'in_progress' ? -1 : 0) - (c.status === 'in_progress' ? -1 : 0) || (a.stage === c.stage ? 0 : a.stage === 'group' ? -1 : 1) || a.round - c.round || a.slot - c.slot)
    .slice(0, 4);
  if (!upcoming.length) return null;
  return (
    <section aria-label={t('Up next')}>
      <h3 className="mb-2 flex items-center gap-2 text-sm font-semibold"><Swords className="h-4 w-4 text-accent" aria-hidden />{t('Up next')}</h3>
      <div className="grid gap-2 md:grid-cols-2">{upcoming.map((m) => <MatchCard key={m.id} m={m} names={names} />)}</div>
    </section>
  );
}
